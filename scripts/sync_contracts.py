#!/usr/bin/env python3
"""Regenerate the complete, immutable Shared bundle and Rust include inventory.

Read Git blobs rather than mutable working files; validate closure and entry
points before replacing only generated assets. --check compares full inventory,
bytes and provenance, including stale-file removal. No runtime schema retrieval.
Requires Python 3 and PyYAML (maintainer/CI tooling only, never a runtime dependency).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import posixpath
import shutil
import subprocess
from pathlib import Path
from urllib.parse import urlsplit

import yaml

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "contracts/shared"
RUST = ROOT / "src/contracts_embedded.rs"
ENTRIES = {
    "context_uuid": ("control-plane/v1/domain.schema.json", "uuid"),
    "legal_request": ("organisation/v2/legal-actor-enforcement.schema.json", "AssessLegalActorRequest"),
    "legal_response": ("organisation/v2/legal-actor-enforcement.schema.json", "AssessLegalActorResponse"),
    "documentary_request": ("admission/v2/documentary-restriction.schema.json", "DocumentaryRestrictionAssessmentRequest"),
    "documentary_response": ("admission/v2/documentary-restriction.schema.json", "DocumentaryRestrictionAssessmentResponse"),
    "context_request": ("control-plane/v1/platform-context.schema.json", "PlatformContextResolveRequest"),
    "context_response": ("control-plane/v1/platform-context.schema.json", "PlatformContext"),
    "readiness_request": ("payments/v1/merchant-readiness.schema.json", "ReadinessRequest"),
    "money_movement_request": ("payments/v2/money-movement-authority.schema.json", "MoneyMovementAuthorityRequest"),
    "money_movement_decision": ("payments/v2/money-movement-authority.schema.json", "MoneyMovementAuthorityDecision"),
}


def generate(shared: Path) -> tuple[dict[str, bytes], bytes]:
    lock = yaml.safe_load((ROOT / "contracts.lock.yaml").read_bytes())
    pin = lock["source"]["commit"]

    def git(*args: str) -> bytes:
        return subprocess.check_output(["git", "-C", str(shared), *args])

    if git("rev-parse", "HEAD").decode().strip() != pin:
        raise ValueError("Shared checkout must be at the exact lock pin")
    declared = lock["contracts"]
    if len(declared) != len(set(declared)):
        raise ValueError("Duplicate lock paths")
    documents: dict[str, bytes] = {}
    for path in declared:
        if not path.startswith("contracts/") or posixpath.normpath(path) != path:
            raise ValueError(f"Unsafe lock path: {path}")
        documents[path] = git("show", f"{pin}:{path}")

    def walk(node: object, path: str) -> None:
        if isinstance(node, dict):
            for key in ("$ref", "$dynamicRef"):
                ref = node.get(key)
                if isinstance(ref, str):
                    file = ref.split("#", 1)[0]
                    if file:
                        if urlsplit(file).scheme or file.startswith("/"):
                            raise ValueError(f"Remote/absolute reference forbidden: {ref}")
                        target = posixpath.normpath(posixpath.join(posixpath.dirname(path), file))
                        if target not in documents:
                            raise ValueError(f"Declare consumed closure path: {target}")
            for child in node.values():
                walk(child, path)
        elif isinstance(node, list):
            for child in node:
                walk(child, path)

    for path, raw in documents.items():
        if path.endswith(".schema.json"):
            schema = json.loads(raw)
            expected_id = "https://contracts.baobab-platform.com/" + path.removeprefix("contracts/")
            if schema.get("$id") != expected_id:
                raise ValueError(f"Unexpected canonical schema id: {path}")
            walk(schema, path)
    entries = {}
    for name, (path, definition) in ENTRIES.items():
        schema = json.loads(documents["contracts/" + path])
        if definition not in schema["$defs"]:
            raise ValueError(f"Missing owned entry point: {name}")
        entries[name] = path + "#/$defs/" + definition
    manifest = {
        "repository": lock["source"]["repository"], "commit": pin,
        "entries": entries,
        "files": {path.removeprefix("contracts/"): hashlib.sha256(raw).hexdigest()
                  for path, raw in sorted(documents.items())},
    }
    files = {path.removeprefix("contracts/"): raw for path, raw in documents.items()}
    files["provenance.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    rust = "// Generated by scripts/sync_contracts.py; edit the lock/owner, not this file.\n"
    rust += 'pub const PROVENANCE: &str = include_str!("../contracts/shared/provenance.json");\n'
    rust += 'pub const SHARED_COMMIT: &str = "' + pin + '";\n'
    rust += "#[rustfmt::skip]\npub const EMBEDDED: &[(&str, &str)] = &[\n"
    for path in sorted(manifest["files"]):
        rust += f'    ("{path}", include_str!("../contracts/shared/{path}")),\n'
    rust += "];\n#[rustfmt::skip]\npub const ENTRIES: &[(&str, &str)] = &[\n"
    for name, ref in sorted(entries.items()):
        rust += f'    ("{name}", "{ref}"),\n'
    rust += "];\n"
    return files, rust.encode()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shared-checkout", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, rust = generate(args.shared_checkout)
    if args.check:
        actual = {str(p.relative_to(TARGET)): p.read_bytes()
                  for p in TARGET.rglob("*") if p.is_file()}
        if actual != files or RUST.read_bytes() != rust:
            raise ValueError("Generated bundle differs (bytes, provenance or complete inventory)")
    else:
        # Hand-written source lives outside the generated directory.
        if TARGET.exists():
            shutil.rmtree(TARGET)
        for path, raw in files.items():
            out = TARGET / path
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(raw)
        RUST.write_bytes(rust)
    print(f"Exact Shared bundle verified: {len(files) - 1} files, {len(ENTRIES)} entries")


if __name__ == "__main__":
    main()
